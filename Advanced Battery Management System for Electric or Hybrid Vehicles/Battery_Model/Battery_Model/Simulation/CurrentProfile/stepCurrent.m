function I = stepCurrent(t)

% ==========================================================
% Step Current Profile
%
% 0-100 s     -> 5 A
% 100-200 s   -> 15 A
% 200-300 s   -> 8 A
% ==========================================================

I = zeros(size(t));

I(t<100)=5;

I(t>=100 & t<200)=15;

I(t>=200)=8;

end