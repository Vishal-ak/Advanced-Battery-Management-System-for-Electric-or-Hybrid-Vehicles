function tests = testPackDatabaseNormalization
% Tests for commercial pack database unit parsing and derived fields.
tests = functiontests(localfunctions);
end

function testMilliampHourAndWeightUnits(testCase)
raw = table( ...
    ["48 V";"72 V"], ...
    ["3350mAh";"20 Ah"], ...
    ["1.625 A";"2 A"], ...
    ["6.5 A";"10 A"], ...
    ["48.5 g";"1.2 kg"], ...
    ["13S6P";"20S5P"], ...
    ["200*150*100";"300x200x150"], ...
    'VariableNames',{'NominalVoltage_V','NominalCapacity_Ah', ...
    'ChargeCurrent_A','MaxDischargeCurrent_A','Weight_kg', ...
    'Configuration','Dimensions_mm'});

clean = cleanPackDatabase(raw);
verifyEqual(testCase,clean.NominalCapacity_Ah(1),3.35,'AbsTol',1e-12);
verifyEqual(testCase,clean.NominalCapacity_Ah(2),20,'AbsTol',1e-12);
verifyEqual(testCase,clean.Weight_kg(1),0.0485,'AbsTol',1e-12);
verifyEqual(testCase,clean.Weight_kg(2),1.2,'AbsTol',1e-12);
verifyEqual(testCase,clean.TotalCells,[78;100]);
verifyEqual(testCase,clean.Volume_L(1),3,'AbsTol',1e-12);
end

function testNumericWorkbookColumnsRemainInDeclaredUnits(testCase)
raw = table(48,20,2,10,1.5,"13S6P","200*150*100", ...
    'VariableNames',{'NominalVoltage_V','NominalCapacity_Ah', ...
    'ChargeCurrent_A','MaxDischargeCurrent_A','Weight_kg', ...
    'Configuration','Dimensions_mm'});
clean = cleanPackDatabase(raw);
verifyEqual(testCase,clean.NominalVoltage_V,48);
verifyEqual(testCase,clean.NominalCapacity_Ah,20);
verifyEqual(testCase,clean.Weight_kg,1.5);
end
